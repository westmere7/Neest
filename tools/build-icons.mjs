// Builds Neest's icons from the nest logo (public/logo/Nest_logo.svg: the mark's shape; its colour in
// the file does not matter): the tab favicon (public/favicon.svg, the bare mark in the accent of the
// browser's light or dark setting), the PNG favicon (public/favicon.png 192 px, the bare mark on
// transparent), the home-screen icon (public/logo.png 512 px: platforms fill the square, so the mark
// sits on the app's light background, maskable-safe) and the paths the in-app mark uses
// (src/components/nestMark.ts, coloured by the theme).
// Run `node tools/build-icons.mjs` after changing the logo.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const src = await readFile(path.join(root, 'public/logo/Nest_logo.svg'), 'utf8');
const viewBox = /viewBox="([^"]+)"/.exec(src)[1].split(/[\s,]+/).map(Number);
const paths = [...src.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
if (!paths.length) throw new Error('No paths in Nest_logo.svg');
const [, , vw, vh] = viewBox;

// App theme (src/styles/tokens.css): the accent in light and in dark mode, and the light background.
const LIGHT = '#16684a';
const DARK = '#63c39f';
const PAPER = '#f6f7f8';

/** The mark placed in a 100 × 100 square, `h` units tall, centred. */
function placed(h) {
  const s = h / vh;
  const x = (100 - vw * s) / 2;
  const y = (100 - h) / 2;
  return `<g transform="translate(${x.toFixed(3)} ${y.toFixed(3)}) scale(${s.toFixed(6)})">${paths.map((d) => `<path d="${d}"/>`).join('')}</g>`;
}

// Tab favicon: the bare mark, following the browser's light / dark setting.
const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><style>.m{fill:${LIGHT}}@media (prefers-color-scheme:dark){.m{fill:${DARK}}}</style><g class="m">${placed(96)}</g></svg>\n`;
await writeFile(path.join(root, 'public/favicon.svg'), favicon);

// PNG favicon (fallback for browsers without SVG favicons, and the PWA's "any" icon): the bare mark
// in the light accent on a transparent ground.
const bare = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><g fill="${LIGHT}">${placed(96)}</g></svg>`;
await sharp(Buffer.from(bare), { density: Math.ceil((72 * 192) / 100) }).resize(192, 192).png().toFile(path.join(root, 'public/favicon.png'));

// Home-screen icon (apple-touch, maskable): platforms fill transparency (iOS with black), so the mark
// sits on the app's light background, inside the maskable safe zone.
const appIcon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><rect width="100" height="100" fill="${PAPER}"/><g fill="${LIGHT}">${placed(56)}</g></svg>`;
await sharp(Buffer.from(appIcon), { density: Math.ceil((72 * 512) / 100) }).resize(512, 512).png().toFile(path.join(root, 'public/logo.png'));

// The in-app mark (Logo.tsx draws it in the theme's accent).
const ts = `// Generated by tools/build-icons.mjs from public/logo/Nest_logo.svg. Do not edit by hand.
/** The nest mark's view box and paths (single colour). */
export const NEST_MARK = {
  viewBox: '${viewBox.join(' ')}',
  width: ${vw},
  height: ${vh},
  paths: ${JSON.stringify(paths, null, 2).replace(/\n/g, '\n  ')},
} as const;
`;
await writeFile(path.join(root, 'src/components/nestMark.ts'), ts);
console.log(`icons: ${paths.length} paths → favicon.svg, favicon.png (192), logo.png (512), nestMark.ts`);
